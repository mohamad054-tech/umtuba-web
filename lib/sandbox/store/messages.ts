export function catalogHasArabicScript(locale: AppLocale): boolean {
  if (locale !== "ar") return true;
  return /[\u0600-\u06FF]/.test(storeT("ar", "heroTitle") + storeT("ar", "addToCart") + storeT("ar", "checkoutTitle"));
}
